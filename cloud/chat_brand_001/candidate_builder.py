"""Build the CHAT-BRAND-001 candidate (owner 2026-11-13: one task, one install).

1. The «Зв'язатися з менеджером» button the same on every page: ua_chat_button.py (live since CHAT-BUTTON-001) gets the
   CHAT-BUTTON-002 phone rules (larger, bottom centre; owner «да» 2026-11-12) and resets the older page layers, so the
   pill has one size everywhere; the Korea auctions pages get the button (they still show the old green circle).
2. The logo as a clear way home: ua_brand_home.py (new) adds a thin gold ring around the «UA» mark and a small
   «← На головну» caption under the company name (not on the home page itself).
3. The SEO landing pages get the floating button too (owner «да» 2026-11-13; they have none).
4. «Ми на AUTO.RIA» with the official logo at the bottom of every page: ua_autoria_badge.py (new) adds the home page
   badge where it is missing and shows the logo in place of the plain text on the Korea pages.
5. AUTO.RIA's own wording on the home page reviews button (ua_autoria_text.py, new; their message to the owner).

Every page writer gets the blocks: site_ge_inject.inject_html (cards, catalogue, home, order page) through a wrapper
appended at the end of the module, ua_seo_index.refresh (landings) in its chain. ua_seo_metadata SEO_REVISION: the CRM
sync republishes every card once. The golden catalogue and the static public pages get the blocks now; rollback
restores them byte for byte.
"""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
MODULE = 'ua_chat_button.py'
NEW_MODULES = ('ua_autoria_badge.py', 'ua_autoria_text.py', 'ua_brand_home.py')
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the landing writer; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/info.html', 'video/privacy.html',
         'video/korea.html', 'video/ru/korea.html')
PAGE_GLOBS = ('video/seo/gu/*.html',)
TAG = 'CHAT-BRAND-001'
REVISION = re.compile(r"^SEO_REVISION = '[A-Z0-9-]+'$", re.M)
NEW_REVISION = "SEO_REVISION = '%s'" % TAG
OLD_MARK = '<!--UA-CHAT-GLASS-V1-->'
INJECT_TAIL = ("\n\n# CHAT-BRAND-001: the logo as a clear way home; «Ми на AUTO.RIA» with the logo on every page.\n"
               "_ua_brand_base_inject = inject_html\n"
               "def inject_html(source):\n"
               "    import ua_autoria_badge\n"
               "    import ua_autoria_text\n"
               "    import ua_brand_home\n"
               "    return ua_brand_home.apply(ua_autoria_badge.apply(ua_autoria_text.apply(_ua_brand_base_inject(source))))\n")
CHAIN = "ua_chat_button.apply(ua_social_links.apply(ua_own_counter.apply(ua_google_tag.apply(html))))"
EDITS = {
    'site_ge_inject.py': [],  # INJECT_TAIL appended
    'ua_seo_index.py': [
        ("import ua_chat_button  # CHAT-BUTTON-001\n",
         "import ua_chat_button  # CHAT-BUTTON-001\nimport ua_autoria_badge  # CHAT-BRAND-001\n"
         "import ua_brand_home  # CHAT-BRAND-001\n"),
        (CHAIN, "ua_brand_home.apply(ua_autoria_badge.apply(%s, add_link=True)))" % CHAIN[:-1]),
    ],
    'ua_seo_metadata.py': [],  # SEO_REVISION only
}
DEPENDENCY_SHA256 = {}


def page_names(root):
    root = Path(root)
    found = [name for name in PAGES if (root/name).is_file()]
    for pattern in PAGE_GLOBS:
        found += sorted(p.relative_to(root).as_posix() for p in root.glob(pattern))
    return tuple(found)


def targets(root):
    """Existing files the candidate replaces (the new module is added beside them)."""
    return (MODULE,) + tuple(EDITS) + (GOLDEN,) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    if TAG in text:
        raise ValueError('CHAT_BRAND_ALREADY_APPLIED:' + name)
    for old, new in EDITS[name]:
        if text.count(old) != 1:
            raise ValueError('CHAT_BRAND_EDIT:%s:%d' % (name, text.count(old)))
        text = text.replace(old, new)
    if name == 'site_ge_inject.py':
        if 'def inject_html(' not in text or '_ua_chat_base_inject' not in text:
            raise ValueError('CHAT_BRAND_INJECT_MISSING')
        text = text.rstrip('\n') + INJECT_TAIL
    if name == 'ua_seo_metadata.py':
        if len(REVISION.findall(text)) != 1:
            raise ValueError('CHAT_BRAND_REVISION')
        text = REVISION.sub(NEW_REVISION, text)
    return text.encode('utf-8')


def page(html, landing=False):
    """A page with the current blocks (the button, the AUTO.RIA badge, the logo); a landing page also gets the floating
    button link when it has none (owner «да» 2026-11-13)."""
    import ua_autoria_badge
    import ua_autoria_text
    import ua_brand_home
    import ua_chat_button
    return ua_brand_home.apply(ua_autoria_badge.apply(ua_autoria_text.apply(ua_chat_button.apply(html, add_link=landing))))


def is_landing(name):
    return name.startswith('video/seo/')


def build(source, dependencies):
    """{name: new bytes}; the live button module must be the CHAT-BUTTON-001 one; unchanged pages are left out."""
    module = (HERE/MODULE).read_bytes()
    if source[MODULE] == module:
        raise ValueError('CHAT_BRAND_ALREADY_APPLIED:' + MODULE)
    if OLD_MARK.encode() not in source[MODULE] or b'max-width:767px' in source[MODULE]:
        raise ValueError('CHAT_BRAND_LIVE_MODULE_UNEXPECTED')
    result = {MODULE: module}
    result.update({name: (HERE/name).read_bytes() for name in NEW_MODULES})
    for name, value in source.items():
        if name == MODULE:
            continue
        if name in EDITS:
            result[name] = edit(name, value)
            continue
        changed = page(value.decode('utf-8'), is_landing(name)).encode('utf-8')
        if name == GOLDEN and changed == value:
            raise ValueError('CHAT_BRAND_GOLDEN_UNCHANGED')
        if changed != value:
            result[name] = changed
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
