"""Build the SOCIAL-LINKS-001 candidate (owner 2026-11-08/09: Instagram, Telegram, YouTube, TikTok icons in their own
colours at the bottom of every page, and in the company markup).

- ua_social_links.py (new): the profiles, the icon row and apply(html) — the one place to change a link.
- site_ge_inject.inject_html, which every page writer already calls, adds the row: cards, diagnostics, catalogue,
  home, order page at their next write.
- ua_seo_index.refresh adds it to the landing pages; ua_seo_schema.dealer carries the profiles as sameAs.
- catalog_design_golden.html: the catalogue is rebuilt from it, so it carries the row like the live catalogue.
- ua_seo_metadata SEO_REVISION: the CRM sync republishes every card once (with the row).
- Static public pages get the row now (PAGES): written in place, verified by its marker (a later rewrite by the
  CRM sync keeps it through inject_html), removed by rollback without touching anything else.
"""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
NEW_MODULES = ('ua_social_links.py',)
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the landing writer; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/info.html', 'video/privacy.html')
PAGE_GLOBS = ('video/seo/gu/*.html',)
REVISION = re.compile(r"^SEO_REVISION = '[A-Z0-9-]+'$", re.M)
NEW_REVISION = "SEO_REVISION = 'SOCIAL-LINKS-001'"
EDITS = {
    'site_ge_inject.py': [
        ("    return apply(_ua_speed2_base_inject(source))",
         "    return apply(_ua_speed2_base_inject(source))\n\n"
         "# SOCIAL-LINKS-001: the company's social icons at the bottom of every page.\n"
         "_ua_social_base_inject = inject_html\n"
         "def inject_html(source):\n"
         "    import ua_social_links\n"
         "    return ua_social_links.apply(_ua_social_base_inject(source))"),
    ],
    'ua_seo_index.py': [
        ("import ua_own_counter  # UA-OWN-COUNTER-001\n",
         "import ua_own_counter  # UA-OWN-COUNTER-001\nimport ua_social_links  # SOCIAL-LINKS-001\n"),
        ("ua_own_counter.apply(ua_google_tag.apply(html))",
         "ua_social_links.apply(ua_own_counter.apply(ua_google_tag.apply(html)))"),
    ],
    'ua_seo_schema.py': [
        ("import json\n", "import json\n\nimport ua_social_links  # SOCIAL-LINKS-001\n"),
        ("            'image': ORIGIN + '/video/brand/ua-art/share-preview-20260928.jpg',\n",
         "            'image': ORIGIN + '/video/brand/ua-art/share-preview-20260928.jpg',\n"
         "            'sameAs': list(ua_social_links.SAME_AS),\n"),
    ],
    'ua_seo_metadata.py': [],  # SEO_REVISION only
}
DEPENDENCY_SHA256 = {}


def page_names(root):
    root = Path(root)
    found = [name for name in PAGES if (root/name).is_file()]
    for pattern in PAGE_GLOBS:
        found += sorted(p.relative_to(root).as_posix() for p in root.glob(pattern))
    return tuple(found)


def targets(root):
    """Existing files the candidate replaces (the new module is added beside them)."""
    return tuple(EDITS) + (GOLDEN,) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    if 'SOCIAL-LINKS-001' in text:
        raise ValueError('SOCIAL_ALREADY_APPLIED:' + name)
    for old, new in EDITS[name]:
        if text.count(old) != 1:
            raise ValueError('SOCIAL_EDIT:%s:%d' % (name, text.count(old)))
        text = text.replace(old, new)
    if name == 'ua_seo_metadata.py':
        if len(REVISION.findall(text)) != 1:
            raise ValueError('SOCIAL_REVISION')
        text = REVISION.sub(NEW_REVISION, text)
    return text.encode('utf-8')


def build(source, dependencies):
    """{name: new bytes}; pages and the golden catalogue get the icon row, unchanged pages are left out."""
    import ua_social_links
    result = {name: (HERE/name).read_bytes() for name in NEW_MODULES}
    for name, value in source.items():
        if name in EDITS:
            result[name] = edit(name, value)
            continue
        changed = ua_social_links.apply(value.decode('utf-8')).encode('utf-8')
        if name == GOLDEN and changed == value:
            raise ValueError('SOCIAL_GOLDEN_UNCHANGED')
        if changed != value:
            result[name] = changed
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
