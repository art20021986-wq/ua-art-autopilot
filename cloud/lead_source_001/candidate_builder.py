"""Build the LEAD-SOURCE-001 candidate (owner 2026-11-12: every site enquiry says where the visitor came from).

- ua_lead_source.py (new): the new attribution.js text and apply(html), which loads it on a page — one place for the rule.
- video/order/attribution.js gets the new text (a visit from another site keeps that site as its source).
- site_ge_inject.inject_html, which every page writer already calls, loads the script at every page write (appended
  at the end of the module, after the existing chain).
- ua_seo_landings.pages, which the landing writer (ua_seo_index.refresh) calls, loads it on the landing pages
  (appended at the end of the module); the install refreshes the landings.
- catalog_design_golden.html: the catalogue is rebuilt from it.
- Static public pages load it now (PAGES); pages that already load it are left out.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
NEW_MODULES = ('ua_lead_source.py',)
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the landing writer; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/korea.html', 'video/info.html',
         'video/privacy.html')
PAGE_GLOBS = ('video/seo/gu/*.html',)
TAG = 'LEAD-SOURCE-001'
SCRIPT_FILE = 'video/order/attribution.js'
TAILS = {
    'site_ge_inject.py': ("def inject_html(",
                          "\n\n# LEAD-SOURCE-001: every page loads the visit source script (order/attribution.js).\n"
                          "_ua_lead_source_base_inject = inject_html\n"
                          "def inject_html(source):\n"
                          "    import ua_lead_source\n"
                          "    return ua_lead_source.apply(_ua_lead_source_base_inject(source))\n"),
    'ua_seo_landings.py': ("def pages(",
                           "\n\n# LEAD-SOURCE-001: the landing pages load the visit source script (order/attribution.js).\n"
                           "_ua_lead_source_base_pages = pages\n"
                           "def pages(*args, **kwargs):\n"
                           "    import ua_lead_source\n"
                           "    return {k: ua_lead_source.apply(v) for k, v in _ua_lead_source_base_pages(*args, **kwargs).items()}\n"),
}
DEPENDENCY_SHA256 = {}


def page_names(root):
    root = Path(root)
    found = [name for name in PAGES if (root/name).is_file()]
    for pattern in PAGE_GLOBS:
        found += sorted(p.relative_to(root).as_posix() for p in root.glob(pattern))
    return tuple(found)


def targets(root):
    """Existing files the candidate replaces (the new module is added beside them)."""
    return tuple(TAILS) + (GOLDEN, SCRIPT_FILE) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    anchor, tail = TAILS[name]
    if TAG in text:
        raise ValueError('LEAD_SOURCE_ALREADY_APPLIED:' + name)
    if anchor not in text:
        raise ValueError('LEAD_SOURCE_ANCHOR_MISSING:' + name)
    return (text.rstrip('\n') + tail).encode('utf-8')


def build(source, dependencies):
    """{name: new bytes}; the script gets its new text, pages and the golden catalogue load it, unchanged pages are left out."""
    import ua_lead_source
    result = {name: (HERE/name).read_bytes() for name in NEW_MODULES}
    for name, value in source.items():
        if name in TAILS:
            result[name] = edit(name, value)
            continue
        if name == SCRIPT_FILE:
            if 'window.uaAttribution' not in value.decode('utf-8'):
                raise ValueError('LEAD_SOURCE_SCRIPT_UNEXPECTED')
            result[name] = ua_lead_source.JS.encode('utf-8')
            continue
        changed = ua_lead_source.apply(value.decode('utf-8')).encode('utf-8')
        if changed != value:
            result[name] = changed
    if 'video/index.html' not in result:
        raise ValueError('LEAD_SOURCE_HOME_UNCHANGED')
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
