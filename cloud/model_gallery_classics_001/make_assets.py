#!/usr/bin/env python3
"""Build card_assets.py (run from the repository root; needs Pillow, only here, not on the server).

Reads the 8 rare-car photos picked by eye and fetched from Commons (cloud/model_gallery_001/photos7_japan.json, in
the owner's order) and writes the card's gallery entry (empty generation line, photo list with author and licence)
and the photos as 640 px wide WebP, the form of MODEL-GALLERY-001.
"""
import base64
import hashlib
import io
import json
from pathlib import Path

import card

HERE = Path(__file__).resolve().parent
FETCHED = 'cloud/model_gallery_001/photos7_japan.json'
# Different cars, not views: one list in the owner's order; the card name is the whole title.
VIEW = 'front_left'
GENERATION = {'uk': '', 'ru': '', 'ka': ''}
MEDIA = 'video/order/'
WIDTH = 640
QUALITY = 70


def webp(data):
    from PIL import Image
    image = Image.open(io.BytesIO(data)).convert('RGB')
    image.thumbnail((WIDTH, WIDTH * 2), Image.LANCZOS)
    output = io.BytesIO()
    image.save(output, 'WEBP', quality=QUALITY, method=6)
    return output.getvalue(), image.size


def build():
    photos, files = [], {}
    for photo in json.load(open(FETCHED))['models'][card.KEY]['gallery']:
        data, (width, height) = webp(base64.b64decode(photo['b64']))
        # The content hash in the name: browsers never show a cached photo of an earlier release.
        path = 'media/classics-%d-%s.webp' % (len(photos) + 1, hashlib.sha256(data).hexdigest()[:8])
        files[MEDIA + path] = base64.b64encode(data).decode()
        photos.append({'author': photo['artist'], 'height': height, 'license': photo['license'],
                       'license_url': photo['license_url'], 'path': path, 'source': photo['page'],
                       'view': VIEW, 'width': width})
    lines = ['"""Japan rare-car card: gallery entry and photos (generated by make_assets.py)."""',
             'ENTRY = %r' % {'generation': GENERATION, 'photos': photos}, 'FILES = {']
    for path, text in sorted(files.items()):
        lines += ['    %r: (' % path] + ['        %r' % text[i:i + 100] for i in range(0, len(text), 100)] + ['    ),']
    (HERE/'card_assets.py').write_text('\n'.join(lines + ['}']) + '\n')
    return len(photos), sum(len(base64.b64decode(t)) for t in files.values())


if __name__ == '__main__':
    print(build())
