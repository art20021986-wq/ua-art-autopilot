#!/usr/bin/env python3
"""Build the embedded release assets (run from the repository root; needs Pillow, only here, not on the server).

Reads the picked photos fetched from Wikimedia Commons (cloud/model_gallery_001/photos_<group>.json), the live
main photo sizes (cloud/podbor_probe_20261025/live_podbor_r3.json) and the page sources in site/, and writes:
- photos_<letter>.py: the new photos as 640 px wide WebP (base64), each module under the 1 MB bundle limit;
- gallery_assets.py: gallery.js, gallery.css and model-gallery.json (generation line and photo list of each model).
"""
import base64
import glob
import io
import json
from pathlib import Path
import string

import generations

HERE = Path(__file__).resolve().parent
FETCHED = 'cloud/model_gallery_001/photos_*.json'
LIVE = 'cloud/podbor_probe_20261025/live_podbor_r3.json'
MEDIA = 'video/order/'
WIDTH = 640
QUALITY = 70
CHUNK = 760 * 1024
VERSION = '20261026.1'


def webp(data):
    from PIL import Image
    image = Image.open(io.BytesIO(data)).convert('RGB')
    image.thumbnail((WIDTH, WIDTH * 2), Image.LANCZOS)
    output = io.BytesIO()
    image.save(output, 'WEBP', quality=QUALITY, method=6)
    return output.getvalue(), image.size


def main_photos():
    countries = json.load(open(LIVE))['bootstrap']['catalog']['countries']
    return {model['key']: model['media'] for country in countries.values() for model in country['models']}


def module(name, doc, values, extra=''):
    lines = ['"""%s"""' % doc] + ([extra] if extra else []) + ['FILES = {']
    for path, data in sorted(values.items()):
        lines.append('    %r: (' % path)
        text = base64.b64encode(data).decode() if isinstance(data, bytes) else None
        if text is None:
            lines.append('        %r' % data)
        else:
            lines += ['        %r' % text[i:i + 100] for i in range(0, len(text), 100)]
        lines.append('    ),')
    lines.append('}')
    (HERE/name).write_text('\n'.join(lines) + '\n')


def build():
    mains = main_photos()
    gallery, photos = {}, {}
    fetched = {}
    for path in sorted(glob.glob(FETCHED)):
        fetched.update(json.load(open(path))['models'])
    for key in sorted(fetched):
        main = mains[key]
        items = [{'path': main['path'], 'width': main['width'], 'height': main['height']}]
        for view in ('exterior', 'interior'):
            for photo in fetched[key][view]:
                data, (width, height) = webp(base64.b64decode(photo['b64']))
                relative = 'media/%s-%d.webp' % (key, len(items) + 1)
                photos[MEDIA + relative] = data
                items.append({'path': relative, 'width': width, 'height': height, 'source': photo['page'],
                              'author': photo['artist'], 'license': photo['license'],
                              'license_url': photo['license_url']})
        gallery[key] = {'generation': generations.line(key), 'photos': items}
    for old in HERE.glob('photos_*.py'):
        old.unlink()
    chunks, chunk, size = [], {}, 0
    for path, value in sorted(photos.items()):
        if chunk and size + len(value) * 4 // 3 > CHUNK:
            chunks.append(chunk)
            chunk, size = {}, 0
        chunk[path] = value
        size += len(value) * 4 // 3
    chunks.append(chunk)
    names = ['photos_' + letter for letter in string.ascii_lowercase[:len(chunks)]]
    for name, values in zip(names, chunks):
        module(name + '.py', 'Gallery photos (generated by make_assets.py).', values)
    data = json.dumps({'version': VERSION, 'models': gallery}, ensure_ascii=False, sort_keys=True, indent=1) + '\n'
    module('gallery_assets.py', 'Page files of the model gallery release (generated by make_assets.py).',
           {MEDIA + 'gallery.js': (HERE/'site/gallery.js').read_text(),
            MEDIA + 'gallery.css': (HERE/'site/gallery.css').read_text(),
            MEDIA + 'model-gallery.json': data}, 'PHOTO_MODULES = %r' % (tuple(names),))
    return len(photos), sum(len(v) for v in photos.values())


if __name__ == '__main__':
    print(build())
