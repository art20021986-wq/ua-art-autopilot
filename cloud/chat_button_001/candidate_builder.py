"""Build the CHAT-BUTTON-001 candidate (owner 2026-11-10/11, mockup approved: the floating WhatsApp circle becomes a
translucent «Зв'язатися з менеджером» pill on every page; the link stays).

- ua_chat_button.py (new): the style and apply(html) — the one place to change the look.
- site_ge_inject.inject_html, which every page writer already calls, adds it: cards, diagnostics, catalogue,
  home, order page at their next write (appended at the end of the module, after the existing chain).
- ua_seo_index.refresh adds it to the landing pages.
- catalog_design_golden.html: the catalogue is rebuilt from it, so it carries the style like the live catalogue.
- ua_seo_metadata SEO_REVISION: the CRM sync republishes every card once (with the style).
- Static public pages get it now (PAGES): written in place, verified by its marker (a later rewrite by the CRM sync
  keeps it through inject_html), removed by rollback without touching anything else.
  video/korea.html is left to its own pending releases (KOREA-TERMS, KOREA-DAYS-PAGE).
"""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
NEW_MODULES = ('ua_chat_button.py',)
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the landing writer; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/info.html', 'video/privacy.html')
PAGE_GLOBS = ('video/seo/gu/*.html',)
REVISION = re.compile(r"^SEO_REVISION = '[A-Z0-9-]+'$", re.M)
NEW_REVISION = "SEO_REVISION = 'CHAT-BUTTON-001'"
TAG = 'CHAT-BUTTON-001'
INJECT_TAIL = ("\n\n# CHAT-BUTTON-001: the floating «contact a manager» button in one look on every page.\n"
               "_ua_chat_base_inject = inject_html\n"
               "def inject_html(source):\n"
               "    import ua_chat_button\n"
               "    return ua_chat_button.apply(_ua_chat_base_inject(source))\n")
EDITS = {
    'site_ge_inject.py': [],  # INJECT_TAIL appended
    'ua_seo_index.py': [
        ("import ua_social_links  # SOCIAL-LINKS-001\n",
         "import ua_social_links  # SOCIAL-LINKS-001\nimport ua_chat_button  # CHAT-BUTTON-001\n"),
        ("ua_social_links.apply(ua_own_counter.apply(ua_google_tag.apply(html)))",
         "ua_chat_button.apply(ua_social_links.apply(ua_own_counter.apply(ua_google_tag.apply(html))))"),
    ],
    'ua_seo_metadata.py': [],  # SEO_REVISION only
}
DEPENDENCY_SHA256 = {}


def page_names(root):
    root = Path(root)
    found = [name for name in PAGES if (root/name).is_file()]
    for pattern in PAGE_GLOBS:
        found += sorted(p.relative_to(root).as_posix() for p in root.glob(pattern))
    return tuple(found)


def targets(root):
    """Existing files the candidate replaces (the new module is added beside them)."""
    return tuple(EDITS) + (GOLDEN,) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    if TAG in text:
        raise ValueError('CHAT_ALREADY_APPLIED:' + name)
    for old, new in EDITS[name]:
        if text.count(old) != 1:
            raise ValueError('CHAT_EDIT:%s:%d' % (name, text.count(old)))
        text = text.replace(old, new)
    if name == 'site_ge_inject.py':
        if 'def inject_html(' not in text:
            raise ValueError('CHAT_INJECT_MISSING')
        text = text.rstrip('\n') + INJECT_TAIL
    if name == 'ua_seo_metadata.py':
        if len(REVISION.findall(text)) != 1:
            raise ValueError('CHAT_REVISION')
        text = REVISION.sub(NEW_REVISION, text)
    return text.encode('utf-8')


def build(source, dependencies):
    """{name: new bytes}; pages and the golden catalogue get the style, unchanged pages are left out."""
    import ua_chat_button
    result = {name: (HERE/name).read_bytes() for name in NEW_MODULES}
    for name, value in source.items():
        if name in EDITS:
            result[name] = edit(name, value)
            continue
        changed = ua_chat_button.apply(value.decode('utf-8')).encode('utf-8')
        if name == GOLDEN and changed == value:
            raise ValueError('CHAT_GOLDEN_UNCHANGED')
        if changed != value:
            result[name] = changed
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
