"""Build the TERMS-LINKS-001 candidate (owner 2026-11-11: remove the link to the terms page «Умови / Условия и
гарантии» (info.html) everywhere on the site).

- ua_terms_links.py (new): apply(html) drops the link — the one place for the rule.
- site_ge_inject.inject_html, which every page writer already calls, drops it at every page write (appended at the
  end of the module, after the existing chain).
- ua_seo_landings.pages, which the landing writer (ua_seo_index.refresh) calls, drops it from the landing pages
  (appended at the end of the module); the install refreshes the landings.
- catalog_design_golden.html: the catalogue is rebuilt from it.
- Static public pages lose the link now (PAGES): home menu and «Умови, строки та гарантії», catalogue menu, order
  page «Умови купівлі та доставки», Korea page menu, the terms page's own menu. The order page intro is added by
  ua_seo_metadata only when missing, so it is not re-added. The page info.html itself stays.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
NEW_MODULES = ('ua_terms_links.py',)
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the landing writer; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/korea.html', 'video/info.html',
         'video/privacy.html')
PAGE_GLOBS = ('video/seo/gu/*.html',)
TAG = 'TERMS-LINKS-001'
TAILS = {
    'site_ge_inject.py': ("def inject_html(",
                          "\n\n# TERMS-LINKS-001: no link to the terms page (info.html) on any page.\n"
                          "_ua_terms_base_inject = inject_html\n"
                          "def inject_html(source):\n"
                          "    import ua_terms_links\n"
                          "    return ua_terms_links.apply(_ua_terms_base_inject(source))\n"),
    'ua_seo_landings.py': ("def pages(",
                           "\n\n# TERMS-LINKS-001: no link to the terms page (info.html) on the landing pages.\n"
                           "_ua_terms_base_pages = pages\n"
                           "def pages(*args, **kwargs):\n"
                           "    import ua_terms_links\n"
                           "    return {k: ua_terms_links.apply(v) for k, v in _ua_terms_base_pages(*args, **kwargs).items()}\n"),
}
DEPENDENCY_SHA256 = {}


def page_names(root):
    root = Path(root)
    found = [name for name in PAGES if (root/name).is_file()]
    for pattern in PAGE_GLOBS:
        found += sorted(p.relative_to(root).as_posix() for p in root.glob(pattern))
    return tuple(found)


def targets(root):
    """Existing files the candidate replaces (the new module is added beside them)."""
    return tuple(TAILS) + (GOLDEN,) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    anchor, tail = TAILS[name]
    if TAG in text:
        raise ValueError('TERMS_ALREADY_APPLIED:' + name)
    if anchor not in text:
        raise ValueError('TERMS_ANCHOR_MISSING:' + name)
    return (text.rstrip('\n') + tail).encode('utf-8')


def build(source, dependencies):
    """{name: new bytes}; pages and the golden catalogue lose the link, unchanged pages are left out."""
    import ua_terms_links
    result = {name: (HERE/name).read_bytes() for name in NEW_MODULES}
    for name, value in source.items():
        if name in TAILS:
            result[name] = edit(name, value)
            continue
        changed = ua_terms_links.apply(value.decode('utf-8')).encode('utf-8')
        if changed != value:
            result[name] = changed
    if 'video/index.html' not in result:
        raise ValueError('TERMS_HOME_UNCHANGED')
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
