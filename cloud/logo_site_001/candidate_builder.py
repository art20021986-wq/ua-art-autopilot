"""Build the LOGO-001 candidate (owner «Да» 2026-11-28: the new logo C and the «Головна» / «Назад» buttons, one install).

ua_brand_home.py (replaced) is already in every page writer's chain (site_ge_inject.inject_html: cards, catalogue, home,
order page, Korea/Japan/USA pages; ua_seo_index: landings). Its <head> block now carries the new logo C (ua_logo_c.py,
new) instead of the gold ring, and the buttons' style instead of the caption «← На головну»; it writes the buttons
(ua_header_nav.py, new) into the header before the language switch, except on the home page. No page writer is edited.
ua_seo_metadata SEO_REVISION: the CRM sync republishes every card once; the landings are rebuilt by the install's
landing refresh. The golden catalogue and the static public pages get it now; rollback restores them byte for byte.
Texts, links, photos, the language switch, the favicon and CRM data do not change.
"""
import hashlib
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
MODULE = 'ua_brand_home.py'
# The installed copy this release replaces (PERF-CWV-001, installed 2026-11-26: PERF-CWV-INSTALL-20261126-R2 plan).
MODULE_SHA256 = '7525c90bb29307f00c5e7005c81496ba1e2957f105560b8c64b8681099a40cfb'
NEW_MODULES = ('ua_logo_c.py', 'ua_header_nav.py')
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the card or landing writers; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/info.html', 'video/privacy.html',
         'video/korea.html', 'video/ru/korea.html', 'video/japan.html', 'video/usa.html')
TAG = 'LOGO-001'
REVISION = re.compile(r"^SEO_REVISION = '[A-Z0-9-]+'$", re.M)
NEW_REVISION = "SEO_REVISION = '%s'" % TAG
EDITS = ('ua_seo_metadata.py',)
DEPENDENCY_SHA256 = {}


def sha(value):
    return hashlib.sha256(value).hexdigest()


def page_names(root):
    root = Path(root)
    return tuple(name for name in PAGES if (root/name).is_file())


def targets(root):
    """Existing files the candidate replaces (the new modules are added beside them)."""
    return (MODULE,) + EDITS + (GOLDEN,) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    if NEW_REVISION in text:
        raise ValueError('LOGO_ALREADY_APPLIED:' + name)
    if len(REVISION.findall(text)) != 1:
        raise ValueError('LOGO_REVISION')
    return REVISION.sub(NEW_REVISION, text).encode('utf-8')


def page(html):
    """A public page (and the golden catalogue) as the page writers will now produce it."""
    import ua_brand_home
    return ua_brand_home.apply(html)


golden_page = page


def build(source, dependencies):
    """{name: new bytes}; the live logo module must be the PERF-CWV-001 one; unchanged pages are left out."""
    if sha(source[MODULE]) != MODULE_SHA256:
        raise ValueError('LOGO_LIVE_MODULE_UNEXPECTED:' + MODULE)
    result = {MODULE: (HERE/MODULE).read_bytes()}
    result.update({name: (HERE/name).read_bytes() for name in NEW_MODULES})
    for name, value in source.items():
        if name == MODULE:
            continue
        if name in EDITS:
            result[name] = edit(name, value)
            continue
        changed = page(value.decode('utf-8')).encode('utf-8')
        if name == GOLDEN and changed == value:
            raise ValueError('LOGO_GOLDEN_UNCHANGED')
        if changed != value:
            result[name] = changed
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
