"""Build the CHAT-BUTTON-002 candidate (owner «да» 2026-11-12): on phones the «Зв'язатися з менеджером» pill is larger
and sits in the bottom centre of the screen; the Korea auctions pages get the button too (owner «да» 2026-11-12).

- ua_chat_button.py (live since CHAT-BUTTON-001): the phone rules; apply() now puts the current block in place of an
  existing one. Every page writer already calls it (site_ge_inject.inject_html, ua_seo_index.refresh), so cards and
  landings carry the new look at their next write.
- ua_seo_metadata SEO_REVISION: the CRM sync republishes every card once (with the new block).
- catalog_design_golden.html and the static public pages (PAGES): the block replaced now; the Korea pages get it added.
  Rollback restores them byte for byte.
"""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
MODULE = 'ua_chat_button.py'
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the landing writer; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/info.html', 'video/privacy.html',
         'video/korea.html', 'video/ru/korea.html')
PAGE_GLOBS = ('video/seo/gu/*.html',)
REVISION = re.compile(r"^SEO_REVISION = '[A-Z0-9-]+'$", re.M)
NEW_REVISION = "SEO_REVISION = 'CHAT-BUTTON-002'"
EDITS = ('ua_seo_metadata.py',)
OLD_MARK = '<!--UA-CHAT-GLASS-V1-->'
DEPENDENCY_SHA256 = {}


def page_names(root):
    root = Path(root)
    found = [name for name in PAGES if (root/name).is_file()]
    for pattern in PAGE_GLOBS:
        found += sorted(p.relative_to(root).as_posix() for p in root.glob(pattern))
    return tuple(found)


def targets(root):
    """Existing files the candidate replaces."""
    return (MODULE,) + EDITS + (GOLDEN,) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    if NEW_REVISION in text:
        raise ValueError('CHAT2_ALREADY_APPLIED:' + name)
    if len(REVISION.findall(text)) != 1:
        raise ValueError('CHAT2_REVISION')
    return REVISION.sub(NEW_REVISION, text).encode('utf-8')


def build(source, dependencies):
    """{name: new bytes}; the live module must be the CHAT-BUTTON-001 one (it carries the old block marker)."""
    import ua_chat_button
    module = (HERE/MODULE).read_bytes()
    if source[MODULE] == module:
        raise ValueError('CHAT2_ALREADY_APPLIED:' + MODULE)
    if OLD_MARK.encode() not in source[MODULE] or b'max-width:767px' in source[MODULE]:
        raise ValueError('CHAT2_LIVE_MODULE_UNEXPECTED')
    result = {MODULE: module}
    for name, value in source.items():
        if name == MODULE:
            continue
        if name in EDITS:
            result[name] = edit(name, value)
            continue
        changed = ua_chat_button.apply(value.decode('utf-8')).encode('utf-8')
        if name == GOLDEN and changed == value:
            raise ValueError('CHAT2_GOLDEN_UNCHANGED')
        if changed != value:
            result[name] = changed
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
