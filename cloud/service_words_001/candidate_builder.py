"""Build the SERVICE-WORDS-001 candidate (owner 2026-11-12: no «подбор» anywhere on the site; UA ART provides full
support of the car — the approved service text).

- ua_service_words.py (new): apply(html) puts the approved wording in place of every «подбор» phrase — the one place
  for the rule.
- site_ge_inject.inject_html, which every page writer already calls (car cards included), applies it at every page
  write (appended at the end of the module, after the existing chain).
- ua_seo_landings.pages, which the landing writer (ua_seo_index.refresh) calls, applies it to the landing pages
  (appended at the end of the module); the install refreshes the landings.
- catalog_design_golden.html: the catalogue is rebuilt from it.
- Static public pages and the current car card pages change now (PAGES, PAGE_GLOBS). The address podbor.html stays.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
NEW_MODULES = ('ua_service_words.py',)
GOLDEN = 'catalog_design_golden.html'
# Public pages not regenerated by the landing writer; site/ is not served.
PAGES = ('video/index.html', 'video/katalog.html', 'video/podbor.html', 'video/korea.html', 'video/info.html',
         'video/privacy.html')
PAGE_GLOBS = ('video/seo/gu/*.html', 'video/UA-*.html', 'video/ru/UA-*.html', 'video/ua/UA-*.html')
TAG = 'SERVICE-WORDS-001'
TAILS = {
    'site_ge_inject.py': ("def inject_html(",
                          "\n\n# SERVICE-WORDS-001: the approved service wording instead of «подбор» on every page.\n"
                          "_ua_service_base_inject = inject_html\n"
                          "def inject_html(source):\n"
                          "    import ua_service_words\n"
                          "    return ua_service_words.apply(_ua_service_base_inject(source))\n"),
    'ua_seo_landings.py': ("def pages(",
                           "\n\n# SERVICE-WORDS-001: the approved service wording instead of «подбор» on the landing pages.\n"
                           "_ua_service_base_pages = pages\n"
                           "def pages(*args, **kwargs):\n"
                           "    import ua_service_words\n"
                           "    return {k: ua_service_words.apply(v) for k, v in _ua_service_base_pages(*args, **kwargs).items()}\n"),
}
DEPENDENCY_SHA256 = {}


def page_names(root):
    root = Path(root)
    found = [name for name in PAGES if (root/name).is_file()]
    for pattern in PAGE_GLOBS:
        found += sorted(p.relative_to(root).as_posix() for p in root.glob(pattern))
    return tuple(found)


def targets(root):
    """Existing files the candidate replaces (the new module is added beside them)."""
    return tuple(TAILS) + (GOLDEN,) + page_names(root)


def edit(name, value):
    text = value.decode('utf-8')
    anchor, tail = TAILS[name]
    if TAG in text:
        raise ValueError('SERVICE_ALREADY_APPLIED:' + name)
    if anchor not in text:
        raise ValueError('SERVICE_ANCHOR_MISSING:' + name)
    return (text.rstrip('\n') + tail).encode('utf-8')


def build(source, dependencies):
    """{name: new bytes}; pages and the golden catalogue get the approved wording, unchanged pages are left out."""
    import ua_service_words
    result = {name: (HERE/name).read_bytes() for name in NEW_MODULES}
    for name, value in source.items():
        if name in TAILS:
            result[name] = edit(name, value)
            continue
        changed = ua_service_words.apply(value.decode('utf-8')).encode('utf-8')
        if changed != value:
            result[name] = changed
    if 'video/index.html' not in result:
        raise ValueError('SERVICE_HOME_UNCHANGED')
    return result


def is_page(name):
    return name.endswith('.html') and name != GOLDEN
